#!/usr/bin/env python3
"""Generate PRIMER.md: a small always-loaded ROUTER (style, core terms, need->use routes, access notes, protocol).
Everything else stays in glossary.yaml / capabilities.yaml / facts/ and is found via `brain.py search`.
Config: brain.config.yaml. Env: BRAIN_DIR."""
import os, re, glob, sys, yaml
B = os.environ.get("BRAIN_DIR") or os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def clip(s, n):
    s = re.sub(r"\s+", " ", str(s or "")).strip()
    return s if len(s) <= n else s[:n - 1] + "…"

def load(name, default):
    p = os.path.join(B, name)
    return (yaml.safe_load(open(p)) or default) if os.path.exists(p) else default

def render(cfg, gl, skills, style, n):
    org = cfg.get("org", "your org"); role = cfg.get("role", "")
    L = [f"# {org} primer (router)", "",
         "_Generated by `scripts/build_primer.py` from `brain.config.yaml`, `style.md`, `glossary.yaml`. A router: use the lookups below for detail._", "",
         f"You work at {org}" + (f" ({role})." if role else ".") + (f" Repos: `{cfg['repos_root']}/<repo>`." if cfg.get("repos_root") else ""), "",
         style, "", "## Need → use", "| need | use |", "|---|---|"]
    for r in cfg.get("routes") or []: L.append(f"| {r['need']} | {r['use']} |")
    if skills: L.append("| deep knowledge of one system | skill " + ", ".join(f"`{s}`" for s in skills) + " |")
    if cfg.get("access"): L += ["", "## Always-useful access"] + [f"- {a}" for a in cfg["access"]]
    core = sorted((g for g in gl if g.get("core")), key=lambda g: ({"system": 0, "env": 1, "tool": 2, "concept": 3}.get(g.get("kind"), 9), str(g["term"]).lower()))
    if core:
        L += ["", "## Core systems (more terms: `brain.py search` / glossary.yaml)"]
        for g in core:
            L.append(f"- **{g['term']}** — {clip(g.get('one_liner'), n)}" + (f" → `{g['skill']}`" if g.get("skill") else ""))
    L += ["", "## Brain protocol",
          "- Knowledge lives in the brain repo (skill `brain` has the full protocol).",
          "- Pinned workstream: read its STATE.md first, update at milestones. Record durable learnings and user corrections with `brain.py note` (never secrets/PII).",
          "- Facts marked `verified: false` are leads: confirm before relying on them."]
    return "\n".join(L) + "\n"

def build(brain_dir=None):
    global B
    if brain_dir: B = brain_dir
    cfg = load("brain.config.yaml", {}); gl = load("glossary.yaml", [])
    budget = int(os.environ.get("PRIMER_BUDGET") or cfg.get("primer_budget") or 8500)
    skills = sorted(os.path.basename(os.path.dirname(p)) for p in glob.glob(f"{B}/skills/*/SKILL.md"))
    sp = os.path.join(B, "style.md"); style = open(sp).read().strip() if os.path.exists(sp) else ""
    for n in (120, 100, 85, 70):
        out = render(cfg, gl, skills, style, n)
        if len(out) <= budget: break
    return out, len(out) > budget

if __name__ == "__main__":
    out, over = build()
    open(os.path.join(B, "PRIMER.md"), "w").write(out)
    print(f"PRIMER.md {len(out)} chars (~{len(out)//4} tokens)" + (" [OVER BUDGET]" if over else ""))
